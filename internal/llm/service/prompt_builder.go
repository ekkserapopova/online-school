package service

import (
	"fmt"
)

type PromptBuilder struct{}

func NewPromptBuilder() *PromptBuilder {
	return &PromptBuilder{}
}

func (b *PromptBuilder) BuildSystemPrompt() string {
	return "Ты эксперт по оценке кода. Твоя задача - объективно оценивать код строго по критериям из ТЗ. Не вводи свои критерии или требования, которых нет в ТЗ. Если в ТЗ указаны конкретные ограничения (например, типы данных), оценивай только в рамках этих ограничений. Не снижай оценку за отсутствие функций, которые не требуются в ТЗ."
}

func (b *PromptBuilder) BuildEvaluationPrompt(taskDescription, codeToEvaluate string) string {
	res := fmt.Sprintf(`Выполни строгий и объективный анализ следующего кода на соответствие ТЗ, основываясь ТОЛЬКО на указанных требованиях. Предоставь ответ в формате JSON.

ТЕХНИЧЕСКОЕ ЗАДАНИЕ:
%s

КОД ДЛЯ ОЦЕНКИ:
%s

Оцени код СТРОГО по следующим критериям, не добавляя никаких новых требований, которых нет в ТЗ:
1. Корректность реализации(оценка 0-5)
    * Верен ли синтаксис для языка программирования из задания? Если нет - оценка 0 по всем критериям оценивания
    * Соответствует ли код ТЗ? Если нет - оценка 0 по всем критериям оценивания
    * Есть ли логические ошибки в реализации?
    * Дает ли код правильные результаты для ожидаемых входных данных?
2. Обработка краевых случаев(оценка 0-5)
    * Обрабатываются ли пустые входные данные?
    * Какие есть еще основные граничные случаи у задачи? Как код обрабатывает их в рамках ТЗ?
    * Если в ТЗ упомянута обработка ошибок, реализована ли она правильно? 
    * Если обработка ошибок не упомянута в ТЗ, не снижай баллы за ее отсутствие.
3. Эффективность алгоритма(оценка 0-5)
    * Насколько эффективен алгоритм с точки зрения времени выполнения?
    * Насколько эффективен алгоритм с точки зрения использования памяти? 
    * Есть ли возможности для оптимизации?
4. Качество кода(оценка 0-5)
    * Используются ли понятные имена переменных и функций, отражающие их назначение? Если нет: Добавь в код ученеика комментарий на русском языке, поясняющий неверное название, строго в строку с ошибкой! Комментариев должно быть несколько, если неверных названий несколько. нужно только добавить комментарий, не исправляя названия в коде!!!
    * Разбит ли код на логические блоки и функции?

ВАЖНЫЕ ИНСТРУКЦИИ:
- Оценивай код ИСКЛЮЧИТЕЛЬНО на основе требований, указанных в ТЗ, без добавления своих критериев.
- По каждому критерию поставь балл(в соответсвии с требованиями)
- Если название функций, переменных не отражает их назначение, снижай балл за качество кода. ЭТО КРИТИЧЕСКИЙ МОМЕНТ ДЛЯ ДАННОГО КРИТЕРИЯ - добавь комментарии в код к неверным названиям
- Если оценка по критерию максимальная, то пиши только оценку, иначе пиши оценку и только замечания
- Если код написан на питон то нужно опустить типизацию
- Формула для подсчета итоговой оценки: 0,35*Корректность реализации+0,31*Обработка краевых случаев+0,22*Эффективность алгоритма+0,12*Качество кода
- Не снижай баллы за отсутствие функциональности или обработки случаев, которые НЕ УКАЗАНЫ в ТЗ.
- Учитывай, что если в ТЗ явно ограничены типы входных данных (например, "целые числа"), то код не обязан обрабатывать другие типы.
- Замечания по каждому критерию должны отличаться друг от друга, не должно быть такого, что в нескольких критериях написано об одном и том же
- Добавь в код ученеика комментарий на русском языке, поясняющий ошибку, строго в строку с ошибкой! Комментариев должно быть несколько, если ошибок несколько. нужно только добавить комментарий, не исправляя ошибки в коде!!!
- Внимательно проверь код на верный синтаксис(в языке Python - точка с запятой в конце строки - ЭТО ОШИБКА)
- НЕ пиши в конце обратной связи итоговый балл за задание
- Интерпретируй ТЗ буквально, не расширяя и не сужая его смысл по своему усмотрению.`, taskDescription, codeToEvaluate)
	//log.Print(res)
	return res
}
