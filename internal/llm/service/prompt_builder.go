package service

import (
	"fmt"
)

type PromptBuilder struct{}

func NewPromptBuilder() *PromptBuilder {
	return &PromptBuilder{}
}

func (b *PromptBuilder) BuildSystemPrompt() string {
	return "Ты эксперт по оценке кода. Твоя задача - объективно оценивать код строго по критериям из ТЗ. Не вводи свои критерии или требования, которых нет в ТЗ. Если в ТЗ указаны конкретные ограничения (например, типы данных), оценивай только в рамках этих ограничений. Не снижай оценку за отсутствие функций, которые не требуются в ТЗ."
}

func (b *PromptBuilder) BuildEvaluationPrompt(taskDescription, codeToEvaluate string) string {
	return fmt.Sprintf(`Выполни строгий и объективный анализ следующего кода на соответствие ТЗ, основываясь ТОЛЬКО на указанных требованиях. Предоставь ответ в формате JSON.

ТЕХНИЧЕСКОЕ ЗАДАНИЕ:
%s

КОД ДЛЯ ОЦЕНКИ:
%s

Оцени код СТРОГО по следующим критериям, не добавляя никаких новых требований, которых нет в ТЗ:

1. Соответствие требованиям задания (оценка 0-5)
   - Полностью ли функция соответствует ТЗ?
   - Обрабатывает ли функция именно те типы входных данных, которые указаны в ТЗ?
   - Возвращает ли функция результат в нужном формате согласно ТЗ?
   - Верен ли синтаксис для языка программирования из задания? Если нет: -3 от оценки для данного пункта оценивания
   - Не снижай баллы за отсутствие функциональности, которая не упомянута в ТЗ.

2. Корректность реализации (оценка 0-5)
   - Верен ли синтаксис для языка программирования из задания? Если нет - оценка 0 для данного пункта оценивания
   - Правильно ли функция выполняет требуемые в ТЗ операции?
   - Есть ли логические ошибки в реализации?
   - Дает ли код правильные результаты для ожидаемых входных данных?

3. Эффективность алгоритма и оптимизация (оценка 0-5)
   - Насколько эффективен алгоритм с точки зрения времени выполнения?
   - Насколько эффективен алгоритм с точки зрения использования памяти?
   - Есть ли возможности для оптимизации?

4. Обработка граничных случаев и ошибок (оценка 0-5)
   - Как код обрабатывает граничные случаи в рамках ТЗ? 
   - Если в ТЗ упомянута обработка ошибок, реализована ли она правильно?
   - Если обработка ошибок не упомянута в ТЗ, не снижай баллы за ее отсутствие.

ВАЖНЫЕ ИНСТРУКЦИИ:
- Оценивай код ИСКЛЮЧИТЕЛЬНО на основе требований, указанных в ТЗ, без добавления своих критериев.
- По каждому критерию поставь балл(в соответсвии с требованиями)
- Если оценка по критерию максимальная, то пиши только оценку, иначе пиши оценку и только замечания
- Если код написан на питон то нужно опустить типизацию
- Формула для подсчета итоговой оценки: Соответствие требованиям задания(оценка 0-5)*0,31+Корректность реализации(оценка 0-5)*0,31+Обработка граничных случаев и ошибок (оценка 0-5)*0,23+Эффективность алгоритма и оптимизация (оценка 0-5)*0,15
- Не снижай баллы за отсутствие функциональности или обработки случаев, которые НЕ УКАЗАНЫ в ТЗ.
- Учитывай, что если в ТЗ явно ограничены типы входных данных (например, "целые числа"), то код не обязан обрабатывать другие типы.
- Интерпретируй ТЗ буквально, не расширяя и не сужая его смысл по своему усмотрению.`, taskDescription, codeToEvaluate)
}
